// This script generates the first draft of the zigxp file by compairing the ntdll.zig declerations and winxp's ntdll.dll.
// Further manual edits are still required.
// You can reuse this same script for win7 or any other version, you might end up with a lower number of functions that needs a rewrite.

// This is not a very smart implementation and it's not trying to be one.
// The goal of it is just automating some tedious manual work.

const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();

    // ---
    // Getting WinXp functions as HashTable
    // ---
    var table = std.StringHashMap(bool).init(gpa);
    defer table.deinit();

    const bytes = @embedFile("ntdll-winxp.txt");
    var start: usize = 0;
    var last: usize = 0;

    while (start < bytes.len) : (start += 1) {
        if (bytes[start] == '\n') {
            const y = bytes[last .. start - 1];
            try table.put(y, true);
            last = start + 1;
        }
    }
    try table.put(bytes[last..], true);

    // -------
    // Compairing against ntdll definition in std and assembling data in array
    // -------

    // Using reflection for this task is not good since it give us the final resolved types that might not exist or that are private
    // Luckly someone bundeled a full zig parser with this language, how convinient !
    const FunctionInfo = struct {
        lname: []const u8,
        name: []const u8,
        return_type: []const u8,
        param_types: []const []const u8,
        param_names: []const []const u8,
    };
    var functions = std.ArrayList(FunctionInfo).empty;

    const Ast = std.zig.Ast;
    const tree = try Ast.parse(gpa, @embedFile("ntdll.zig"), .{ .mode = .zig });
    if (tree.errors.len != 0) return error.ParseFailed;

    var buf: [1]Ast.Node.Index = undefined;

    for (tree.rootDecls()) |decl| {
        const proto = tree.fullFnProto(&buf, decl) orelse continue;
        const name_tok = proto.name_token orelse continue;
        const name = tree.tokenSlice(name_tok);

        const lname = try gpa.alloc(u8, name.len);
        for (name, 0..) |c, i| {
            lname[i] = if (i == 0) c + ('a' - 'A') else c;
        }

        if (table.contains(name)) continue;

        var param_names: std.ArrayList([]const u8) = .empty;
        var param_types: std.ArrayList([]const u8) = .empty;

        var it = proto.iterate(&tree);
        while (it.next()) |p| {
            try param_names.append(gpa, if (p.name_token) |t| tree.tokenSlice(t) else "_");
            try param_types.append(gpa, if (p.type_expr) |t| tree.getNodeSource(t) else "anytype");
        }

        try functions.append(gpa, .{
            .lname = lname,
            .name = name,
            .param_types = param_types.items,
            .param_names = param_names.items,
            .return_type = if (proto.ast.return_type.unwrap()) |r| tree.getNodeSource(r) else "void",
        });
    }

    // -------
    // Generating Code
    // -------
    const file = try std.Io.Dir.cwd().createFile(init.io, "zigxp.zig.draft", .{});
    var buffer: [4096]u8 = undefined;
    var fw = file.writer(init.io, &buffer);
    const w = &fw.interface;

    try w.print("// This file was autogenerated with zigxp.exe\n", .{});
    try w.print("// It might not be in a usable state, please look for \"zigxp.zig\" instead\n\n", .{});

    try w.print("const std = @import(\"std\");\n", .{});
    try w.print("const windows = std.os.windows;\n\n", .{});

    for (functions.items) |f| {
        try w.print("pub fn {s}(", .{f.lname});

        for (f.param_types, f.param_names) |param, name| {
            var type_start = param.len;
            while (type_start > 0) {
                const c = param[type_start - 1];
                if (c == '*' or c == ' ' or c == '?') break;
                type_start -= 1;
            }

            const is_upper = isAllUpper(param[type_start..]);
            if (is_upper or std.mem.findScalar(u8, param, '.') != null) {
                try w.print("{s}: {s}windows.{s}, ", .{ name, param[0..type_start], param[type_start..] });
            } else {
                try w.print("{s}: {s}, ", .{ name, param });
            }
        }

        var type_start = f.return_type.len;
        while (type_start > 0) {
            const c = f.return_type[type_start - 1];
            if (c == '*' or c == ' ' or c == '?') break;
            type_start -= 1;
        }

        const is_upper = isAllUpper(f.return_type[type_start..]);
        if (is_upper) {
            try w.print(") callconv(.winapi) {s}windows.{s} {{\n", .{ f.return_type[0..type_start], f.return_type[type_start..] });
        } else {
            try w.print(") callconv(.winapi) {s} {{\n", .{f.return_type});
        }

        for (f.param_names) |name| {
            try w.print("_ = {s}; ", .{name});
        }

        if (std.mem.eql(u8, f.return_type, "void") or std.mem.eql(u8, f.return_type, "noreturn")) {
            try w.print("\n}}\n\n", .{});
        } else {
            try w.print("return @fromBackingInt(0);\n}}\n\n", .{});
        }

        try w.writeByte('\n');
    }

    try w.print("comptime {{\n", .{});
    for (functions.items) |f| {
        try w.print("@export(&{s}, .{{.name = \"{s}\"}});\n", .{ f.lname, f.name });
    }
    try w.print("}}\n", .{});

    try w.flush();
}

fn isAllUpper(s: []const u8) bool {
    var is_upper = true;
    for (s) |c| {
        if (std.ascii.isLower(c)) {
            is_upper = false;
            break;
        }
    }
    return is_upper;
}
